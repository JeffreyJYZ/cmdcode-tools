/**
 * The environment layer: variables from `~/.config/opencode/shell-rc.json`'s
 * `env` map, exported into every non-interactive zsh the agent runs.
 *
 * Values are literal, never evaluated. A secret that changes (a token minted on
 * demand) belongs in `~/.config/opencode/shell.zsh`, which runs after this file
 * and can call a command; a config file that names one stays readable in git and
 * in a backup.
 */
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { ENV_FILE } from "./constants/shell-rc";
import { configFile } from "./guards";

/** Read `HOME` per call so tests can point it at a temporary directory. */
const home = (): string => process.env.HOME ?? homedir();

export type Env = Record<string, string>;

/** A name zsh will accept on the left of `export`. */
const VALID_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

/**
 * The configured variables. Anything malformed is dropped rather than written
 * into a script that every command sources: a bad name or a non-string value is
 * a config fault, and one bad line would break every agent shell.
 */
export function loadEnv(): Env {
	try {
		const parsed = JSON.parse(readFileSync(configFile(), "utf8")) as { env?: unknown };
		const values: Env = {};
		if (parsed.env && typeof parsed.env === "object") {
			for (const [name, value] of Object.entries(parsed.env as Record<string, unknown>)) {
				if (!VALID_NAME.test(name) || typeof value !== "string") continue;
				values[name] = value;
			}
		}
		return values;
	} catch {
		return {};
	}
}

/** Single-quote for zsh: the only special character left after that is `'`. */
function quote(value: string): string {
	return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** The script sourced by every agent shell. Empty config = no `export` lines. */
export function renderEnv(values: Env): string {
	const lines = ["# Generated by opencode-shell-rc. Sourced by agent shells only."];
	for (const [name, value] of Object.entries(values)) {
		lines.push(`export ${name}=${quote(value)}`);
	}
	return `${lines.join("\n")}\n`;
}

/**
 * Regenerate `env.zsh` when the config changed. No variables means no file at
 * all, so the shim's `-f` test skips the source instead of reading a no-op
 * script on every command.
 */
export function syncEnv(): boolean {
	const script = renderEnv(loadEnv());
	const path = join(stateDirPath(), ENV_FILE);
	const wanted = script.includes("export ") ? script : undefined;

	if (!wanted) {
		if (!existsSync(path)) return false;
		try {
			rmSync(path, { force: true });
			return true;
		} catch {
			return false;
		}
	}

	let current = "";
	try {
		current = readFileSync(path, "utf8");
	} catch {
		// first run
	}
	if (current === wanted) return false;

	try {
		mkdirSync(stateDirPath(), { recursive: true });
		const temporary = `${path}.tmp`;
		writeFileSync(temporary, wanted);
		renameSync(temporary, path);
		return true;
	} catch {
		return false;
	}
}

/** Kept local to avoid a cycle with `shim.ts` (which imports this module). */
function stateDirPath(): string {
	const base = process.env.XDG_STATE_HOME ?? join(home(), ".local", "state");
	return join(base, "opencode", "shell-rc");
}
