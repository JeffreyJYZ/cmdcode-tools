/**
 * Regenerate mpc's self-contained OpenDesign rate table from core/od.json.
 *
 *   bun scripts/extract-od-rates.ts          # write the generated module
 *   bun scripts/extract-od-rates.ts --check  # fail if the committed file is stale
 *
 * The published tarball ships only `src/`. A static import that climbed out to
 * core/od.json broke every installed path, so the packaged copy lives inside
 * src/ and is generated here. `test/data/od-packaged-rates.test.ts` pins its
 * VALUES against core/od.json; --check pins the exact bytes of this generator.
 */
import od from "../core/od.json";

const ROOT = new URL("..", import.meta.url);
const OUT = new URL("oc-cmd-compare/src/data/sources/od/od.generated.ts", ROOT);
const CHECK = process.argv.includes("--check");

const HEADER = `// GENERATED by scripts/extract-od-rates.ts — do not edit by hand.
// Source: core/od.json (Open Design's own published model-prices list).
// Regenerate: bun scripts/extract-od-rates.ts — drift is caught by
// oc-cmd-compare/test/data/od-packaged-rates.test.ts.
//
// This module lives inside the package on purpose: npm ships only \`src/\`, so
// the installed mpc cannot resolve a path back into the monorepo's core/.

/** One published model row, copied verbatim from core/od.json. */
export interface OdPublishedRow {
\tid: string;
\tlabel: string;
\tcatalogId?: string;
\tmultiplier: number;
\tinput: number;
\toutput: number;
\tcacheRead: number;
\tcacheWrite?: number;
\trateSource?: string;
\tlongContext?: {
\t\tinputTokensAbove: number;
\t\tinput: number;
\t\toutput: number;
\t\tcacheRead: number;
\t\tcacheWrite?: number;
\t};
}

/** Every row in core/od.json, in source order. Read-only. */
export const OD_PUBLISHED_ROWS: readonly OdPublishedRow[] = [
`;

function buildSource(): string {
	const rows = od.models.map((m) => JSON.stringify(m)).join(",\n");
	return `${HEADER}${rows},\n];\n`;
}

async function format(source: string): Promise<string> {
	const proc = Bun.spawn(["bun", "fmt", "--stdin-filepath=od.generated.ts"], {
		cwd: ROOT.pathname,
		stdin: "pipe",
		stdout: "pipe",
		stderr: "pipe",
	});
	proc.stdin.write(source);
	proc.stdin.end();
	const [out, err, code] = await Promise.all([
		new Response(proc.stdout).text(),
		new Response(proc.stderr).text(),
		proc.exited,
	]);
	if (code !== 0) throw new Error(`bun fmt failed (${code}): ${err}`);
	return out;
}

const formatted = await format(buildSource());

if (CHECK) {
	const current = await Bun.file(OUT.pathname).text();
	if (current !== formatted) {
		console.error(
			"[extract-od-rates] GENERATED FILE STALE — run bun scripts/extract-od-rates.ts",
		);
		process.exit(1);
	}
	console.log(`[extract-od-rates] ${od.models.length} rows match (bytes identical)`);
} else {
	await Bun.write(OUT.pathname, formatted);
	console.log(`[extract-od-rates] wrote ${OUT.pathname} (${od.models.length} rows)`);
}
